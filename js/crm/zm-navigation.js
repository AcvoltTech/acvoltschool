function renderZoomRecordings() {
  var recs = getZoomRecs().filter(function(r) { return r.visible !== false; }).sort(function(a,b) { return new Date(b.date) - new Date(a.date); });

  // Filter by student groups (non-admin only)
  var isAdmin = (typeof isAdminAuthenticated === 'function' && isAdminAuthenticated()) ||
                (typeof isAdminStudent === 'function' && isAdminStudent());
  if (!isAdmin) {
    var session = getZoomSession();
    var userEmail = session ? session.email : (typeof currentUser !== 'undefined' && currentUser ? currentUser.email : '');
    var userGroups = getStudentGroupsForEmail(userEmail);
    // Log group count only (avoid exposing PII in console)
    console.log('[Zoom Filter] groups:', userGroups.length);
    recs = recs.filter(function(r) {
      if (!r.groups || r.groups.length === 0) return true; // No groups = visible to all
      if (userGroups.length === 0) return false; // User not in any group can only see unassigned ("Todos")
      return r.groups.some(function(g) { return userGroups.indexOf(g) !== -1; });
    });
  }

  var _zoomSearchEl = document.getElementById('zoomSearchInput');
  var search = (_zoomSearchEl ? _zoomSearchEl.value : '').toLowerCase();
  var watched = getZoomWatched();
  var now = new Date();
  var dayOfWeek = now.getDay();
  var diffToMon = (dayOfWeek === 0) ? 6 : (dayOfWeek - 1);
  var startOfWeek = new Date(now.getFullYear(), now.getMonth(), now.getDate() - diffToMon);
  startOfWeek.setHours(0,0,0,0);
  var startOfMonth = new Date(now.getFullYear(), now.getMonth(), 1);
  var startOfLastMonth = new Date(now.getFullYear(), now.getMonth() - 1, 1);
  var endOfLastMonth = new Date(now.getFullYear(), now.getMonth(), 0, 23, 59, 59, 999);

  var filtered = recs.filter(function(r) {
    var d = new Date(r.date);
    var isWatched = watched.indexOf(r.id) !== -1;
    switch (zoomCardFilter) {
      case 'thisWeek': if (!(d >= startOfWeek)) return false; break;
      case 'thisMonth': if (!(d >= startOfMonth && d < startOfWeek)) return false; break;
      case 'lastMonth': if (!(d >= startOfLastMonth && d <= endOfLastMonth)) return false; break;
      case 'older': if (!(d < startOfLastMonth)) return false; break;
      case 'unwatched': if (isWatched) return false; break;
      case 'watched': if (!isWatched) return false; break;
    }
    if (search && r.title.toLowerCase().indexOf(search) === -1) return false;
    return true;
  });

  if (filtered.length === 0) {
    document.getElementById('zoomRecordingsContainer').innerHTML = '<div style="text-align:center;padding:40px;color:#94a3b8;"><div style="font-size:40px;margin-bottom:10px;">📹</div><p>' + _t('zmn_no_classes','No hay clases disponibles') + (search ? _t('zmn_search_suffix',' para "') + _escHtml(search) + '"' : '') + '</p></div>';
    return;
  }

  var html = '';
  var lastDate = '';
  filtered.forEach(function(r) {
    var d = new Date(r.date);
    var dateStr = d.toLocaleDateString('es-MX', { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' });
    dateStr = dateStr.charAt(0).toUpperCase() + dateStr.slice(1);
    if (dateStr !== lastDate) {
      html += '<div style="font-size:14px;font-weight:800;color:#1e293b;margin:18px 0 8px;padding:6px 0;border-bottom:2px solid #e2e8f0;">' + dateStr + '</div>';
      lastDate = dateStr;
    }
    var isWatched = watched.indexOf(r.id) !== -1;
    var durText = r.duration_min ? Math.floor(r.duration_min/60) + 'h ' + (r.duration_min%60) + 'min' : '';
    html += '<div style="background:#fff;border:1px solid ' + (isWatched ? '#bbf7d0' : '#e2e8f0') + ';border-radius:12px;padding:12px;margin-bottom:8px;' + (isWatched ? 'opacity:0.7;' : '') + '">';
    html += '<div style="display:flex;align-items:center;gap:10px;">';
    html += '<div style="width:42px;height:42px;background:' + (isWatched ? 'linear-gradient(135deg,#27ae60,#2ecc71)' : 'linear-gradient(135deg,#2D8CFF,#0B5CFF)') + ';border-radius:10px;display:flex;align-items:center;justify-content:center;font-size:18px;flex-shrink:0;">' + (isWatched ? '✅' : '📹') + '</div>';
    html += '<div style="flex:1;min-width:0;">';
    html += '<div style="font-size:15px;font-weight:800;color:#0f172a;white-space:nowrap;overflow:hidden;text-overflow:ellipsis;">' + _escHtml(r.title) + '</div>';
    html += '<div style="font-size:13px;color:#1e293b;font-weight:600;margin-top:3px;">' + _escHtml(r.day_label || '') + (durText ? ' · ' + durText : '') + '</div>';
    html += '</div>';
    html += '</div>';
    html += '<div style="display:flex;gap:6px;margin-top:8px;">';
    html += '<button onclick="openZoomRec(\'' + r.id + '\')" style="flex:1;padding:8px;background:linear-gradient(135deg,#2D8CFF,#0B5CFF);color:#fff;border:none;border-radius:8px;font-size:12px;font-weight:700;cursor:pointer;">' + _t('zmn_view_class_btn','▶️ Ver Clase') + '</button>';
    if (!isWatched) {
      html += '<button onclick="markZoomWatched(\'' + r.id + '\')" style="padding:8px 12px;background:#f0fdf4;color:#27ae60;border:1px solid #bbf7d0;border-radius:8px;font-size:11px;cursor:pointer;">✅</button>';
    }
    html += '</div></div>';
  });
  document.getElementById('zoomRecordingsContainer').innerHTML = html;
}

function openZoomRec(id) {
  var recs = getZoomRecs();
  var rec = recs.find(function(r) { return r.id === id; });
  if (rec && rec.link) {
    // Double-check group access (non-admin)
    var isAdmin = (typeof isAdminAuthenticated === 'function' && isAdminAuthenticated()) ||
                  (typeof isAdminStudent === 'function' && isAdminStudent());
    if (!isAdmin && rec.groups && rec.groups.length > 0) {
      var session = getZoomSession();
      var userEmail = session ? session.email : (typeof currentUser !== 'undefined' && currentUser ? currentUser.email : '');
      var userGroups = getStudentGroupsForEmail(userEmail);
      var hasAccess = rec.groups.some(function(g) { return userGroups.indexOf(g) !== -1; });
      if (!hasAccess) {
        alert(_t('zmn_no_class_access','⛔ No tienes acceso a esta clase. Contacta a Maestro Mario.'));
        return;
      }
    }
    // Log view
    var session = getZoomSession();
    var log = JSON.parse(localStorage.getItem('zoom_view_log') || '[]');
    log.push({ id: id, user: session ? session.email : '', ts: Date.now() });
    localStorage.setItem('zoom_view_log', JSON.stringify(log));
    window.open(rec.link, '_blank');
  }
}

function markZoomWatched(id) {
  var w = getZoomWatched();
  if (w.indexOf(id) === -1) { w.push(id); saveZoomWatched(w); }
  renderZoomRecordings();
  updateZoomCardCounts();
}

