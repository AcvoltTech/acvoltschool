function setCrmMode(mode, skipNav) {
  document.getElementById('crmModeAdmin').classList.toggle('crm-mode-active', mode === 'admin');
  document.getElementById('crmModeInstructor').classList.toggle('crm-mode-active', mode === 'instructor');

  // Show/hide sidebar items based on data-crm-mode
  var nav = document.getElementById('crmSidebarNav');
  if (nav) {
    var items = nav.querySelectorAll('[data-crm-mode]');
    items.forEach(function(el) {
      var itemMode = el.getAttribute('data-crm-mode');
      if (itemMode === 'all') {
        el.style.display = '';
      } else if (mode === 'admin') {
        // Admin sees everything
        el.style.display = '';
      } else {
        // Instructor sees only 'all' and 'instructor' items
        el.style.display = (itemMode === 'instructor') ? '' : 'none';
      }
    });
  }

  // Editor role: show only allowed admin sections
  // Mario 2026-05-29: added 'streaming' so Manuel (editor) can run live streams.
  var editorRole = sessionStorage.getItem('admin_role') || currentAdminRole || '';
  if (editorRole === 'editor' && nav) {
    var allowedSections = ['dashboard', 'bandeja', 'tutorialVideos', 'clases', 'zoomResumenes', 'streaming'];
    var sidebarItems = nav.querySelectorAll('[data-crm-section]');
    sidebarItems.forEach(function(el) {
      var sec = el.getAttribute('data-crm-section');
      if (allowedSections.indexOf(sec) === -1) {
        el.style.display = 'none';
      }
    });
    // Hide section labels that have no visible children
    var sectionLabels = nav.querySelectorAll('.crm-sidebar-section');
    sectionLabels.forEach(function(label) {
      var next = label.nextElementSibling;
      var hasVisible = false;
      while (next && !next.classList.contains('crm-sidebar-section')) {
        if (next.style.display !== 'none' && next.hasAttribute('data-crm-section')) {
          hasVisible = true;
          break;
        }
        next = next.nextElementSibling;
      }
      if (!hasVisible) label.style.display = 'none';
    });
  }

  // Técnico de Video role: show only dashboard + streaming
  var tvRole = sessionStorage.getItem('admin_role') || currentAdminRole || '';
  if (tvRole === 'tecnico_video' && nav) {
    var tvAllowedSections = ['dashboard', 'streaming'];
    var tvSidebarItems = nav.querySelectorAll('[data-crm-section]');
    tvSidebarItems.forEach(function(el) {
      var sec = el.getAttribute('data-crm-section');
      if (tvAllowedSections.indexOf(sec) === -1) {
        el.style.display = 'none';
      }
    });
    var tvSectionLabels = nav.querySelectorAll('.crm-sidebar-section');
    tvSectionLabels.forEach(function(label) {
      var next = label.nextElementSibling;
      var hasVisible = false;
      while (next && !next.classList.contains('crm-sidebar-section')) {
        if (next.style.display !== 'none' && next.hasAttribute('data-crm-section')) {
          hasVisible = true;
          break;
        }
        next = next.nextElementSibling;
      }
      if (!hasVisible) label.style.display = 'none';
    });
  }

  // Persist choice
  localStorage.setItem('crmMode', mode);

  // Navigate to dashboard only on explicit mode switch (not on init)
  if (!skipNav) {
    showCrmSection('dashboard', document.querySelector('[data-crm-section="dashboard"]'));
  }
}
/* ========== CRM COLOR OVERRIDE ENGINE ========== */
(function() {
  var darkBgs = ['#1a1a2e','#16213e','#0f172a','#1e293b','#334155','#2d2d44','#252540','#0d1b2a','#1a2332','#2c3e50','#34495e','#444444','#444','#333','#222'];
  var darkGradients = ['linear-gradient(135deg, #1a1a2e','linear-gradient(135deg,#1a1a2e','linear-gradient(135deg, #16213e','linear-gradient(135deg,#16213e','linear-gradient(135deg, #0f172a','linear-gradient(135deg,#0f172a'];

  function isAdminActive() {
    return document.body.classList.contains('crm-redesign');
  }

  function lightenAdminPanel() {
    if (!isAdminActive()) return;
    var adminScreen = document.getElementById('adminDashboardScreen');
    if (!adminScreen) return;
    var allEls = adminScreen.querySelectorAll('*');
    allEls.forEach(function(el) {
      var s = el.style;
      if (!s || !s.cssText) return;
      var css = s.cssText.toLowerCase();

      // Skip sidebar, topbar, and their children
      if (el.closest && (el.closest('.crm-sidebar') || el.closest('.crm-topbar') || el.closest('.crm-welcome-banner'))) return;

      // Fix dark backgrounds
      var bg = s.background || s.backgroundColor || '';
      bg = bg.toLowerCase();
      var hasDarkBg = false;
      darkBgs.forEach(function(d) {
        if (bg.indexOf(d) !== -1) hasDarkBg = true;
      });
      darkGradients.forEach(function(d) {
        if (bg.indexOf(d.toLowerCase()) !== -1) hasDarkBg = true;
      });
      if (bg.indexOf('rgba(0') !== -1 && bg.indexOf('0.') !== -1) {
        // rgba(0,0,0,0.X) — semi-transparent dark
        var match = bg.match(/rgba\(0\s*,\s*0\s*,\s*0\s*,\s*([\d.]+)/);
        if (match && parseFloat(match[1]) > 0.4) hasDarkBg = true;
      }
      // rgba(255,255,255,0.1) type - dark transparent white on dark bg
      if (bg.indexOf('rgba(255') !== -1) {
        var match2 = bg.match(/rgba\(255\s*,\s*255\s*,\s*255\s*,\s*([\d.]+)/);
        if (match2 && parseFloat(match2[1]) < 0.3) {
          // This is a semi-transparent white button on dark bg — make it solid
          if (el.tagName === 'BUTTON' || el.tagName === 'SELECT') {
            s.background = '#f1f5f9';
            s.color = '#1e293b';
            s.border = '1px solid #d1d5db';
            hasDarkBg = false;
          }
        }
      }

      if (hasDarkBg) {
        // Determine what type of element
        var tag = el.tagName;
        if (tag === 'INPUT' || tag === 'SELECT' || tag === 'TEXTAREA') {
          s.background = 'white';
          s.backgroundColor = 'white';
          s.color = '#1e293b';
          s.border = '1px solid #d1d5db';
        } else if (tag === 'BUTTON') {
          // Keep buttons colored but ensure readable
          if (s.color === '#fff' || s.color === 'white' || s.color === 'rgb(255, 255, 255)') {
            // Colored action button — keep it
          } else {
            s.background = '#f1f5f9';
            s.color = '#1e293b';
          }
        } else {
          // Container div — lighten it
          s.background = '#f8fafc';
          s.backgroundColor = '#f8fafc';
          // Fix child text colors
          if (s.color === '#ccc' || s.color === '#fff' || s.color === 'white' || s.color === 'rgb(204, 204, 204)' || s.color === 'rgb(255, 255, 255)') {
            s.color = '#1e293b';
          }
          s.borderColor = '#e2e8f0';
        }
      }

      // Fix light text on now-light backgrounds
      var clr = (s.color || '').toLowerCase();
      if (clr === '#ccc' || clr === '#ddd' || clr === '#aaa' || clr === 'rgb(204, 204, 204)') {
        if (!el.closest || (!el.closest('.crm-sidebar') && !el.closest('.crm-topbar'))) {
          s.color = '#64748b';
        }
      }
      if (clr === '#fff' || clr === 'white' || clr === 'rgb(255, 255, 255)') {
        var parentBg = (el.parentElement && el.parentElement.style.background || '').toLowerCase();
        var isOnColoredBtn = el.closest && el.closest('button');
        if (!isOnColoredBtn && !el.closest('.crm-sidebar') && !el.closest('.crm-topbar')) {
          var elBg = (s.background || s.backgroundColor || '').toLowerCase();
          var hasColoredBg = ['#e74c3c','#3498db','#27ae60','#2ecc71','#9b59b6','#f39c12','#7c3aed','#dc2626','#16803c','#2563eb'].some(function(c) { return elBg.indexOf(c) !== -1; });
          if (!hasColoredBg) {
            s.color = '#1e293b';
          }
        }
      }

      // Fix badge colors like #d4a5ff (purple light text)
      if (clr === '#d4a5ff' || clr === '#ff8a80') {
        s.color = '#6b21a8';
      }
    });
  }

  // Run on mutations (scoped to admin screen only, debounced)
  var _lightenTimer = null;
  var adminScreen = document.getElementById('adminDashboardScreen');
  if (adminScreen) {
    var observer = new MutationObserver(function() {
      if (_lightenTimer) return;
      _lightenTimer = setTimeout(function() { _lightenTimer = null; if (isAdminActive()) lightenAdminPanel(); }, 300);
    });
    observer.observe(adminScreen, { childList: true, subtree: true });
  }

  // Also run periodically but less frequently
  setInterval(function() {
    if (isAdminActive()) lightenAdminPanel();
  }, 5000);

  // Run on initial load
  document.addEventListener('DOMContentLoaded', function() {
    setTimeout(lightenAdminPanel, 1000);
    setTimeout(lightenAdminPanel, 3000);
  });
})();
