async function generateFromPastedText() {
  var title = ((document.getElementById('zmPasteTitle') || {}).value || '').trim();
  var content = ((document.getElementById('zmPasteContent') || {}).value || '').trim();
  var category = (document.getElementById('zmPasteCategory') || {}).value || 'General';
  var numQuestions = parseInt((document.getElementById('zmPasteNumQ') || {}).value) || 15;
  var questionType = (document.getElementById('zmPasteQType') || {}).value || 'mixed';
  var instructions = (document.getElementById('zmPasteInstructions') || {}).value || '';

  if (!content || content.length < 50) {
    alert(_t('edm_min_50'));
    return;
  }
  if (!title) title = 'Texto pegado — ' + new Date().toLocaleDateString('es-MX');
  numQuestions = Math.max(5, Math.min(100, numQuestions));

  var btn = document.getElementById('zmPasteSubmitBtn');
  var progressDiv = document.getElementById('zmPasteProgress');
  var progressBar = document.getElementById('zmPasteProgressBar');
  var statusEl = document.getElementById('zmPasteStatus');

  btn.disabled = true;
  btn.textContent = '⏳ ' + _t('edm_generating', 'Generando...');
  progressDiv.style.display = 'block';

  // Truncate to 100k chars
  if (content.length > 100000) content = content.substring(0, 100000);

  try {
    // Save as material record for tracking
    var insertRes = await supabaseClient.from('zm_materials').insert({
      title: title,
      material_type: 'text',
      file_name: 'texto-pegado',
      file_size: content.length,
      extracted_text: content.substring(0, 10000),
      category: category,
      status: 'processing'
    }).select().single();
    var materialId = (insertRes.data || {}).id || null;

    // Generate in batches of 15
    var BATCH_SIZE = 15;
    var batches = [];
    var remaining = numQuestions;
    while (remaining > 0) {
      batches.push(Math.min(remaining, BATCH_SIZE));
      remaining -= BATCH_SIZE;
    }

    var totalGenerated = 0;
    for (var b = 0; b < batches.length; b++) {
      var batchNum = batches[b];
      var pct = Math.round(((b) / batches.length) * 90) + 5;
      progressBar.style.width = pct + '%';
      statusEl.textContent = '🤖 ' + _t('edm_batch', 'Lote ') + (b + 1) + '/' + batches.length + _t('edm_gen_q', ': generando ') + batchNum + _t('edm_q_label', ' preguntas...');

      var requestBody = {
        textContent: content,
        materialId: materialId,
        title: title,
        numQuestions: batchNum,
        questionType: questionType,
        customInstructions: instructions.trim() + (batches.length > 1 ? '\nEste es lote ' + (b + 1) + ' de ' + batches.length + '. NO repitas preguntas anteriores.' : ''),
        admin_email: getAdminEmail()
      };

      var response = await fetch(SUPABASE_URL + '/functions/v1/generate-exam-questions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'apikey': SUPABASE_KEY,
          'Authorization': 'Bearer ' + SUPABASE_KEY
        },
        body: JSON.stringify(requestBody)
      });

      var result = await response.json();
      if (!response.ok || result.error) {
        console.error('[PasteText] Batch ' + (b + 1) + ' error:', result.error);
        if (b === 0) throw new Error(result.error || 'Error generando preguntas');
        break;
      }
      totalGenerated += result.questionsGenerated || 0;
    }

    // Update material record
    if (materialId) {
      await supabaseClient.from('zm_materials').update({
        status: 'processed',
        questions_generated: totalGenerated
      }).eq('id', materialId);
    }

    progressBar.style.width = '100%';
    progressBar.style.background = '#22c55e';
    statusEl.textContent = '✅ ' + totalGenerated + _t('edm_gen_ok', ' preguntas generadas!');

    if (typeof showNotification === 'function') {
      showNotification('✅ ' + totalGenerated + _t('edm_gen_from_paste', ' preguntas generadas desde texto pegado!'), 'success');
    }

    setTimeout(function() {
      var modal = document.getElementById('zmPasteTextModal');
      if (modal) modal.remove();
      if (typeof loadMaterials === 'function') loadMaterials();
      if (typeof loadGeneratedQuestions === 'function') loadGeneratedQuestions();
    }, 1500);

  } catch (error) {
    console.error('[PasteText] Error:', error);
    progressBar.style.width = '100%';
    progressBar.style.background = '#ef4444';
    statusEl.textContent = '❌ ' + error.message;
    if (typeof showNotification === 'function') {
      showNotification('❌ Error: ' + error.message, 'error');
    }
    btn.disabled = false;
    btn.textContent = '🤖 ' + _t('edm_generate', 'Generar Preguntas');
  }
}

function ensurePdfJs() {
  return new Promise(function(resolve, reject) {
    if (_pdfJsLoaded && window.pdfjsLib) { resolve(); return; }
    var script = document.createElement('script');
    script.src = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/4.0.379/pdf.min.mjs';
    script.type = 'module';
    // pdf.js 4.x is ESM-only, use the legacy build for script-tag compat
    script.src = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.min.js';
    script.type = 'text/javascript';
    script.onload = function() {
      if (window.pdfjsLib) {
        window.pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js';
      }
      _pdfJsLoaded = true;
      resolve();
    };
    script.onerror = function() { reject(new Error('No se pudo cargar pdf.js')); };
    document.head.appendChild(script);
  });
}

// Render a PDF page to a base64 image for Claude vision (scanned PDF fallback)
async function renderPdfPageToImage(file, pageNum) {
  await ensurePdfJs();
  var arrayBuffer = await file.arrayBuffer();
  var pdf = await window.pdfjsLib.getDocument({ data: arrayBuffer }).promise;
  var page = await pdf.getPage(Math.min(pageNum || 1, pdf.numPages));
  var scale = 2; // 2x for readability
  var viewport = page.getViewport({ scale: scale });
  var canvas = document.createElement('canvas');
  canvas.width = viewport.width;
  canvas.height = viewport.height;
  var ctx = canvas.getContext('2d');
  await page.render({ canvasContext: ctx, viewport: viewport }).promise;
  var dataUrl = canvas.toDataURL('image/jpeg', 0.85);
  canvas = null; // Free memory
  return dataUrl;
}

async function extractPdfText(file, fromPage, toPage) {
  await ensurePdfJs();
  var arrayBuffer = await file.arrayBuffer();
  var pdf = await window.pdfjsLib.getDocument({ data: arrayBuffer }).promise;
  var totalPages = pdf.numPages;
  var startPage = Math.max(1, fromPage || 1);
  var endPage = Math.min(totalPages, toPage || totalPages, 30); // Cap at 30 pages
  var allText = '';
  for (var i = startPage; i <= endPage; i++) {
    var page = await pdf.getPage(i);
    var textContent = await page.getTextContent();
    var pageText = textContent.items.map(function(item) { return item.str; }).join(' ');
    allText += pageText + '\n\n';
  }
  return { text: allText.trim(), totalPages: totalPages, pagesProcessed: endPage - startPage + 1 };
}

