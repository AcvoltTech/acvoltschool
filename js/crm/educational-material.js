async function generateQuestionsFromMaterial(materialId, numQuestions, questionType, customInstructions) {
  numQuestions = numQuestions || 10;
  questionType = questionType || 'mixed';
  customInstructions = customInstructions || '';

  // Max 15 questions per API call to avoid timeout/token limits
  var BATCH_SIZE = 15;
  var totalRequested = numQuestions;
  var totalGenerated = 0;

  try {
    // Get material record
    var matRes = await supabaseClient.from('zm_materials').select('*').eq('id', materialId).single();
    if (matRes.error || !matRes.data) throw new Error(_t('edm_not_found'));
    var mat = matRes.data;

    // Update status to processing
    await supabaseClient.from('zm_materials').update({ status: 'processing' }).eq('id', materialId);

    // Determine content to send
    var contentPayload = {};
    if (mat.extracted_text && mat.extracted_text.length >= 50) {
      contentPayload.textContent = mat.extracted_text;
    } else if (mat.file_url) {
      contentPayload.imageUrl = mat.file_url;
    } else {
      throw new Error(_t('edm_no_content'));
    }

    // Split into batches
    var batches = [];
    var remaining = totalRequested;
    while (remaining > 0) {
      var batchSize = Math.min(remaining, BATCH_SIZE);
      batches.push(batchSize);
      remaining -= batchSize;
    }

    if (typeof showNotification === 'function') {
      showNotification('🤖 Generando ' + totalRequested + ' preguntas en ' + batches.length + ' lote' + (batches.length > 1 ? 's' : '') + '...', 'info');
    }

    for (var b = 0; b < batches.length; b++) {
      var batchNum = batches[b];

      if (batches.length > 1 && typeof showNotification === 'function') {
        showNotification('🤖 Lote ' + (b + 1) + '/' + batches.length + ': generando ' + batchNum + ' preguntas...', 'info');
      }

      var requestBody = Object.assign({}, contentPayload, {
        materialId: materialId,
        title: mat.title,
        numQuestions: batchNum,
        questionType: questionType,
        customInstructions: customInstructions.trim() + (batches.length > 1 ? '\nIMPORTANTE: Este es el lote ' + (b + 1) + ' de ' + batches.length + '. NO repitas preguntas de lotes anteriores. Genera preguntas DIFERENTES y NUEVAS.' : ''),
        admin_email: getAdminEmail()
      });

      var response = await fetch(SUPABASE_URL + '/functions/v1/generate-exam-questions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'apikey': SUPABASE_KEY,
          'Authorization': 'Bearer ' + SUPABASE_KEY
        },
        body: JSON.stringify(requestBody)
      });

      var result = await response.json();
      if (!response.ok || result.error) {
        console.error('[Material] Batch ' + (b + 1) + ' error:', result.error);
        if (b === 0) throw new Error(result.error || 'Error generando preguntas');
        // If later batches fail, still count what we got
        break;
      }

      totalGenerated += result.questionsGenerated || 0;
    }

    // Update material status
    await supabaseClient.from('zm_materials').update({
      status: 'processed',
      questions_generated: (mat.questions_generated || 0) + totalGenerated
    }).eq('id', materialId);

    if (typeof showNotification === 'function') {
      showNotification('✅ ' + totalGenerated + ' preguntas generadas exitosamente!', 'success');
    }
    loadMaterials();
    if (typeof loadGeneratedQuestions === 'function') loadGeneratedQuestions();
  } catch (error) {
    console.error('[Material] Error generating questions:', error);
    if (typeof showNotification === 'function') {
      showNotification('❌ Error: ' + error.message, 'error');
    }
    // Reset material status on error
    await supabaseClient.from('zm_materials').update({
      status: totalGenerated > 0 ? 'processed' : 'error',
      error_message: totalGenerated > 0 ? null : error.message,
      questions_generated: totalGenerated > 0 ? totalGenerated : (mat ? mat.questions_generated || 0 : 0)
    }).eq('id', materialId).catch(function(e){ console.warn('[Material] status reset failed:', e && e.message || e); });
    loadMaterials();
  }
}

async function resetMaterialStatus(materialId) {
  try {
    await supabaseClient.from('zm_materials').update({ status: 'processed' }).eq('id', materialId);
    if (typeof showNotification === 'function') showNotification('🔄 ' + _t('edm_mat_reset', 'Material reseteado'), 'success');
    loadMaterials();
  } catch(e) { alert('Error: ' + e.message); }
}

async function deleteMaterial(materialId) {
  if (!confirm(_t('edm_delete_confirm', '¿Eliminar este material? Las preguntas generadas se conservarán.'))) return;
  try {
    var res = await supabaseClient.from('zm_materials').delete().eq('id', materialId);
    if (res.error) throw new Error(res.error.message);
    if (typeof showNotification === 'function') {
      showNotification('🗑️ ' + _t('edm_mat_deleted', 'Material eliminado'), 'success');
    }
    loadMaterials();
  } catch (e) {
    console.error('[Material] Error deleting:', e);
    alert(_t('edm_del_error', 'Error eliminando material: ') + e.message);
  }
}

