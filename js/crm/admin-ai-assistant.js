// --- File/Image Handling ---
function _handleAIFileSelect(files) {
  if (!files || !files.length) return;
  for (var i = 0; i < files.length && _adminAIChat.attachments.length < 5; i++) {
    var file = files[i];
    if (file.size > 10 * 1024 * 1024) { alert(_t('aai_file_too_large') + file.name); continue; }
    _readFileAsBase64(file);
  }
  var fileInput = document.getElementById('adminAIFileInput');
  if (fileInput) fileInput.value = '';
}

function _readFileAsBase64(file) {
  var reader = new FileReader();
  reader.onload = function(e) {
    var dataUrl = e.target.result;
    var base64 = dataUrl.split(',')[1];
    var mediaType = file.type || 'image/png';
    _adminAIChat.attachments.push({
      name: file.name,
      mediaType: mediaType,
      base64: base64,
      dataUrl: dataUrl,
      isImage: mediaType.startsWith('image/')
    });
    _updateAIAttachmentUI();
  };
  reader.readAsDataURL(file);
}

function _removeAIAttachment(idx) {
  _adminAIChat.attachments.splice(idx, 1);
  _updateAIAttachmentUI();
}

function _updateAIAttachmentUI() {
  var container = document.getElementById('adminAIAttachments');
  if (!container) return;
  var atts = _adminAIChat.attachments;
  if (atts.length === 0) { container.style.display = 'none'; container.innerHTML = ''; return; }
  container.style.display = 'flex';
  var html = '';
  atts.forEach(function(a, i) {
    html += '<div class="ai-attach-thumb">';
    if (a.isImage) {
      html += '<img src="' + a.dataUrl + '" alt="' + _escHtml(a.name) + '" />';
    } else {
      html += '<div class="ai-attach-file-icon">&#128196;</div>';
    }
    html += '<button class="ai-attach-remove" onclick="_removeAIAttachment(' + i + ')">&#10005;</button>';
    html += '</div>';
  });
  container.innerHTML = html;
}

