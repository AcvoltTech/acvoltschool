async function sendAdminAIChat(presetMsg) {
  if (_adminAIChat.busy) return;
  var userMsg = presetMsg || (document.getElementById('adminAIInput') || {}).value || '';
  userMsg = userMsg.trim();
  var hasAttachments = _adminAIChat.attachments.length > 0;
  if (!userMsg && !hasAttachments) return;

  var input = document.getElementById('adminAIInput');
  if (input) { input.value = ''; input.style.height = 'auto'; }

  // Capture current attachments then clear
  var currentAttachments = _adminAIChat.attachments.slice();
  _adminAIChat.attachments = [];
  _updateAIAttachmentUI();

  _adminAIChat.busy = true;

  // Store display text and image thumbnails for chat history
  var historyEntry = { role: 'user', content: userMsg || _t('aai_image_attached', '(imagen adjunta)'), displayText: userMsg || '📷 ' + _t('aai_img_sent') };
  if (currentAttachments.length > 0) {
    historyEntry.images = currentAttachments.filter(function(a) { return a.isImage; }).map(function(a) { return a.dataUrl; });
    if (!userMsg) historyEntry.displayText = '📷 ' + currentAttachments.length + _t('aai_imgs_sent');
  }
  _adminAIChat.history.push(historyEntry);

  var msgsDiv = document.getElementById('adminAIMsgs');
  if (msgsDiv) {
    msgsDiv.innerHTML = _renderAdminAIChatHistory() + '<div style="text-align:left;margin-bottom:6px;"><span style="display:inline-block;background:#f1f5f9;color:#94a3b8;padding:6px 12px;border-radius:8px;font-size:11px;">&#129302; ' + _t('aai_analyzing', 'Analizando...') + '</span></div>';
    msgsDiv.scrollTop = msgsDiv.scrollHeight;
  }

  try {
    var section = _adminAIChat.currentSection;
    var isZM = (section === 'zonaMaestro' || section === 'zoomResumenes');
    var contextData = isZM ? await _getAdminAIContext(_adminAIChat.currentTab) : await _getAdminAISectionContext(section);
    var sectionLabel = isZM ? (_adminAITabLabel(_adminAIChat.currentTab) || _adminAIChat.currentTab) : (_adminAISectionLabel(section) || section);
    var visibleContent = _getVisibleCrmContent();

    // Build API messages with multi-modal support
    var apiMessages = [];
    for (var i = 0; i < _adminAIChat.history.length; i++) {
      var m = _adminAIChat.history[i];
      if (m.role !== 'user') {
        apiMessages.push({ role: 'assistant', content: m.content });
        continue;
      }
      // For the first user message, prepend context
      var textContent = m.content;
      if (i === 0) {
        textContent = 'SECCIÓN ACTUAL: ' + sectionLabel + '\n\nDATOS DEL SISTEMA:\n' + contextData;
        if (visibleContent) textContent += '\n\nCONTENIDO VISIBLE EN PANTALLA:\n' + visibleContent;
        textContent += '\n\nCONSULTA: ' + m.content;
      }

      // Check if this message has image attachments (only the latest user message)
      var isLatestUserMsg = (i === _adminAIChat.history.length - 1);
      if (isLatestUserMsg && currentAttachments.length > 0) {
        // Build multi-modal content array
        var contentBlocks = [];
        currentAttachments.forEach(function(att) {
          if (att.isImage) {
            contentBlocks.push({
              type: 'image',
              source: { type: 'base64', media_type: att.mediaType, data: att.base64 }
            });
          }
        });
        contentBlocks.push({ type: 'text', text: textContent });
        apiMessages.push({ role: 'user', content: contentBlocks });
      } else {
        apiMessages.push({ role: 'user', content: textContent });
      }
    }

    var response = await fetch(INSTRUCTOR_AI_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + (SUPABASE_KEY) },
      body: JSON.stringify({
        messages: apiMessages,
        system: ADMIN_AI_SYSTEM,
        max_tokens: 2000,
        admin_email: getAdminEmail()
      })
    });

    if (!response.ok) {
      var errText = await response.text();
      throw new Error('Error ' + response.status + ': ' + errText);
    }
    var result = await response.json();
    var aiReply = (result.reply || result.content || _t('aai_no_response')).trim();
    _adminAIChat.history.push({ role: 'assistant', content: aiReply });
  } catch(e) {
    _adminAIChat.history.push({ role: 'assistant', content: 'Error: ' + e.message });
  }

  _adminAIChat.busy = false;
  if (msgsDiv) {
    msgsDiv.innerHTML = _renderAdminAIChatHistory();
    msgsDiv.scrollTop = msgsDiv.scrollHeight;
  }
}

function _renderAdminAIChatHistory() {
  var html = '';
  _adminAIChat.history.forEach(function(msg) {
    if (msg.role === 'user') {
      html += '<div style="text-align:right;margin-bottom:8px;"><span style="display:inline-block;background:#6366f1;color:#fff;padding:6px 12px;border-radius:10px 10px 2px 10px;font-size:11px;max-width:85%;text-align:left;line-height:1.4;">' + _escHtml(msg.displayText || msg.content) + '</span>';
      // Show image thumbnails in user messages
      if (msg.images && msg.images.length > 0) {
        msg.images.forEach(function(img) {
          // Only allow safe data: URLs for images — prevent javascript: or other protocol injection
          if (typeof img === 'string' && img.match(/^data:image\/(png|jpeg|jpg|gif|webp|bmp|svg\+xml);base64,/i)) {
            html += '<br><img class="ai-user-img" src="' + _escHtml(img) + '" />';
          }
        });
      }
      html += '</div>';
    } else {
      html += '<div style="text-align:left;margin-bottom:8px;"><span style="display:inline-block;background:#f1f5f9;border:1px solid #e2e8f0;color:#334155;padding:6px 12px;border-radius:10px 10px 10px 2px;font-size:11px;max-width:85%;text-align:left;line-height:1.5;">' + _renderAIMarkdown(msg.content) + '</span></div>';
    }
  });
  return html;
}

