function _getExamAssignment() {
  var type = (document.getElementById('cemAssignType') || {}).value || 'all';
  if (type === 'all') return { type: 'all', assigned_to: [], groups: [] };
  if (type === 'group') {
    var selectedGroups = [];
    STUDENT_GROUP_DEFS.forEach(function(g) {
      var cb = document.getElementById('cemGroup_' + g.id);
      if (cb && cb.checked) selectedGroups.push(g.id);
    });
    return { type: 'group', groups: selectedGroups, assigned_to: [] };
  }
  if (type === 'section') {
    var sectionId = (document.getElementById('cemSectionSelect') || {}).value;
    return { type: 'section', section_id: sectionId || null, assigned_to: [], groups: [] };
  }
  if (type === 'students') {
    return { type: 'students', assigned_to: Array.from(_cemSelectedStudents), groups: [] };
  }
  return { type: 'all', assigned_to: [], groups: [] };
}

async function submitCreateExam(examType) {
  var title = (document.getElementById('cemTitle') || {}).value || '';
  var description = (document.getElementById('cemDescription') || {}).value || '';
  var timeLimit = parseInt((document.getElementById('cemTimeLimit') || {}).value) || 30;
  var passingScore = parseInt((document.getElementById('cemPassingScore') || {}).value) || 70;

  if (!title.trim()) { alert(_t('exam_title_req')); return; }
  if (_cemSelectedIds.size === 0) { alert(_t('exam_select_q_req')); return; }

  // Build questions JSONB array from selected approved questions
  var questions = _cemApprovedQuestions.filter(function(q) { return _cemSelectedIds.has(q.id); }).map(function(q) {
    return {
      source_id: q.id,
      question: q.question,
      options: q.options || [],
      correct: typeof q.correct === 'number' ? q.correct : 0,
      explanation: q.explanation || '',
      category: q.category || '',
      difficulty: q.difficulty || 'medium',
      image_url: q.image_url || null
    };
  });

  try {
    var assignment = _getExamAssignment();
    if (assignment.type === 'section' && !assignment.section_id) {
      alert(_t('exam_select_sec_req'));
      return;
    }
    if (assignment.type === 'students' && assignment.assigned_to.length === 0) {
      alert(_t('exam_select_stu_req'));
      return;
    }
    if (assignment.type === 'group' && (!assignment.groups || assignment.groups.length === 0)) {
      alert(_t('exam_select_grp_req'));
      return;
    }

    var area = (document.getElementById('cemArea') || {}).value || 'General';
    var res = await supabaseClient.from('zm_exams').insert([{
      title: title.trim(),
      description: description.trim() || null,
      exam_type: examType,
      area: area,
      questions: questions,
      time_limit: timeLimit,
      passing_score: passingScore,
      status: 'published',
      published_at: new Date().toISOString(),
      section_id: assignment.section_id || null,
      assigned_to: assignment.assigned_to || [],
      target_groups: assignment.groups || []
    }]);
    if (res.error) throw res.error;

    // Send notifications to targeted students
    var insertedExam = (res.data && res.data[0]) || {};
    try {
      var examTitle = title.trim() || _t('exm_new_exam', 'Nuevo Examen');
      var result = await _resolveExamRecipients({
        assigned_to: assignment.assigned_to || [],
        target_groups: assignment.groups || [],
        title: examTitle
      });
      var notifBody = '📝 ' + examTitle;
      if (result.groupNames) notifBody += ' (' + _t('exm_group_word', 'Grupo') + ': ' + result.groupNames + ')';
      notifyStudents(_t('exm_new_exam_assigned', 'Nuevo Examen Asignado'), notifBody, 'examen', result.emails);
    } catch(ne) { console.warn('[Push] create exam notify error:', ne); }

    alert('✅ ' + _t('exam_created_ok'));
    var overlay = document.getElementById('createExamOverlay');
    if (overlay) overlay.remove();
    loadExams();
  } catch(e) { alert(_t('exam_create_err') + e.message); }
}

