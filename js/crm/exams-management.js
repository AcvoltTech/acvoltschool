function toggleSelectAllExamQuestions() {
  var catFilter = (document.getElementById('cemFilterCategory') || {}).value || 'all';
  var diffFilter = (document.getElementById('cemFilterDifficulty') || {}).value || 'all';
  var filtered = _cemApprovedQuestions.filter(function(q) {
    if (catFilter !== 'all' && q.category !== catFilter) return false;
    if (diffFilter !== 'all' && q.difficulty !== diffFilter) return false;
    return true;
  });
  var allSelected = filtered.every(function(q) { return _cemSelectedIds.has(q.id); });
  if (allSelected) {
    filtered.forEach(function(q) { _cemSelectedIds.delete(q.id); });
  } else {
    filtered.forEach(function(q) { _cemSelectedIds.add(q.id); });
  }
  var el = document.getElementById('cemSelectedCount');
  if (el) el.textContent = _cemSelectedIds.size + ' ' + _t('exm_q_selected_suffix', 'preguntas seleccionadas');
  _renderCreateExamQuestions();
}

