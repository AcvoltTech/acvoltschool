  window.saDeleteManual = async function(id) {
    if (!confirm(_t('adm_sa_confirm_delete_manual'))) return;
    try {
      var manual = _saManuals.find(function(m) { return m.id === id; });
      var res = await supabaseClient.from('soporte_manuals').delete().eq('id', id);
      if (res.error) throw res.error;

      // Try to delete file from storage
      if (manual && manual.file_url) {
        try {
          var urlParts = manual.file_url.split('/school-files/');
          if (urlParts[1]) {
            await supabaseClient.storage.from('school-files').remove([decodeURIComponent(urlParts[1])]);
          }
        } catch(se) { console.warn('Storage cleanup skipped:', se); }
      }

      saLoadManuals();
    } catch(e) {
      alert(_t('adm_sa_error_delete') + e.message);
    }
  };

