  window.saRespondTicket = async function(id) {
    var textarea = document.getElementById('saReply_' + id);
    var selectEl = document.getElementById('saState_' + id);
    if (!textarea || !selectEl) return;
    var reply = textarea.value.trim();
    if (!reply) { alert(_t('adm_sa_write_before_send')); return; }

    var newState = selectEl.value || 'en_proceso';
    try {
      var ticket = _saTickets.find(function(t) { return t.id === id; });
      var res = await supabaseClient.from('soporte_tickets').update({
        admin_response: reply,
        responded_by: _saCurrentEmail() || 'admin',
        responded_at: new Date().toISOString(),
        estado: newState
      }).eq('id', id);

      if (res.error) throw res.error;

      // Push notification to student
      if (typeof notifyStudents === 'function' && ticket && ticket.student_email) {
        notifyStudents(
          _t('adm_sa_support_response'),
          _t('adm_sa_ticket_responded').replace('{subject}', ticket.subject || 'Soporte'),
          'soporte',
          [ticket.student_email]
        );
      }

      saLoadTickets();
    } catch(e) {
      alert(_t('adm_sa_error_respond') + e.message);
    }
  };

  window.saChangeState = async function(id) {
    var selectEl = document.getElementById('saState_' + id);
    if (!selectEl) return;
    var newState = selectEl.value;

    try {
      var res = await supabaseClient.from('soporte_tickets').update({
        estado: newState
      }).eq('id', id);

      if (res.error) throw res.error;
      saLoadTickets();
    } catch(e) {
      alert(_t('adm_sa_error_change_state') + e.message);
    }
  };

