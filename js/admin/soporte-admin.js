  window.saDeleteVideo = async function(id) {
    if (!confirm(_t('adm_sa_confirm_delete_video'))) return;
    try {
      var video = _saVideos.find(function(v) { return v.id === id; });
      var res = await supabaseClient.from('soporte_videos').delete().eq('id', id);
      if (res.error) throw res.error;

      // Try to delete file + thumb from storage
      if (video) {
        try {
          var paths = [];
          if (video.video_url) {
            var vParts = video.video_url.split('/school-files/');
            if (vParts[1]) paths.push(decodeURIComponent(vParts[1]));
          }
          if (video.thumbnail_url) {
            var tParts = video.thumbnail_url.split('/school-files/');
            if (tParts[1]) paths.push(decodeURIComponent(tParts[1]));
          }
          if (paths.length > 0) {
            await supabaseClient.storage.from('school-files').remove(paths);
          }
        } catch(se) { console.warn('Storage cleanup skipped:', se); }
      }

      saLoadVideos();
    } catch(e) {
      alert(_t('adm_sa_error_delete') + e.message);
    }
  };

  // ============================================
  // VIDEO HELPERS — Frame extraction + Duration
  // ============================================
  function _saExtractFrame(videoFile) {
    return new Promise(function(resolve, reject) {
      var video = document.createElement('video');
      video.preload = 'metadata';
      video.muted = true;
      video.playsInline = true;
      var url = URL.createObjectURL(videoFile);
      video.src = url;
      video.onloadedmetadata = function() { video.currentTime = video.duration * 0.25; };
      video.onseeked = function() {
        try {
          var canvas = document.createElement('canvas');
          canvas.width = Math.min(video.videoWidth, 1280);
          canvas.height = Math.round(canvas.width * (video.videoHeight / video.videoWidth));
          var ctx = canvas.getContext('2d');
          ctx.drawImage(video, 0, 0, canvas.width, canvas.height);
          canvas.toBlob(function(blob) {
            URL.revokeObjectURL(url);
            if (blob) resolve(new File([blob], 'thumb.jpg', { type: 'image/jpeg' }));
            else reject(new Error('Frame extraction failed'));
          }, 'image/jpeg', 0.85);
        } catch(e) { URL.revokeObjectURL(url); reject(e); }
      };
      video.onerror = function() { URL.revokeObjectURL(url); reject(new Error('Video load error')); };
      setTimeout(function() { URL.revokeObjectURL(url); reject(new Error('Timeout')); }, 15000);
    });
  }

  function _saGetDuration(videoFile) {
    return new Promise(function(resolve, reject) {
      var video = document.createElement('video');
      video.preload = 'metadata';
      video.muted = true;
      var url = URL.createObjectURL(videoFile);
      video.src = url;
      video.onloadedmetadata = function() { URL.revokeObjectURL(url); resolve(video.duration || 0); };
      video.onerror = function() { URL.revokeObjectURL(url); reject(new Error('Duration error')); };
      setTimeout(function() { URL.revokeObjectURL(url); resolve(0); }, 10000);
    });
  }

