  window.saSaveManual = async function(editId) {
    var title = (document.getElementById('saManTitle').value || '').trim();
    if (!title) { alert(_t('adm_sa_enter_title_manual')); return; }

    var btn = document.getElementById('saManSubmitBtn');
    btn.disabled = true;
    btn.textContent = '\u23F3 ' + _t('adm_sa_saving');

    try {
      var row = {
        title: title,
        description: (document.getElementById('saManDesc').value || '').trim() || null,
        brand: (document.getElementById('saManBrand').value || '').trim() || null,
        model: (document.getElementById('saManModel').value || '').trim() || null,
        category: document.getElementById('saManCategory').value || 'installation',
        equipment_type: document.getElementById('saManEquip').value || 'mini-split',
        requires_membership: document.getElementById('saManMembership').checked
      };

      if (editId) {
        // Update existing
        var updRes = await supabaseClient.from('soporte_manuals').update(row).eq('id', editId);
        if (updRes.error) throw updRes.error;
      } else {
        // New upload — file required
        if (!_saSelectedFile) { alert(_t('adm_sa_select_pdf')); btn.disabled = false; btn.textContent = _t('adm_sa_upload_manual'); return; }

        var ts = Date.now();
        var safeName = _saSelectedFile.name.replace(/[^a-zA-Z0-9._-]/g, '_');
        var path = 'soporte/manuals/' + ts + '_' + safeName;

        var upRes = await supabaseClient.storage.from('school-files').upload(path, _saSelectedFile, { cacheControl: '3600', upsert: false });
        if (upRes.error) throw upRes.error;

        var pubUrl = supabaseClient.storage.from('school-files').getPublicUrl(path);
        row.file_url = pubUrl.data ? pubUrl.data.publicUrl : '';
        row.file_size_bytes = _saSelectedFile.size;
        row.uploaded_by = _saCurrentEmail() || 'admin';

        var insRes = await supabaseClient.from('soporte_manuals').insert(row);
        if (insRes.error) throw insRes.error;
      }

      saCloseModal();
      saLoadManuals();
    } catch(e) {
      alert(_t('adm_sa_error_saving_manual') + e.message);
      btn.disabled = false;
      btn.textContent = editId ? _t('adm_sa_save_changes') : _t('adm_sa_upload_manual');
    }
  };

