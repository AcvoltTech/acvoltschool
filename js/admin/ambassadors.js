    async function saveNewClass(btn) {
      var title = document.getElementById('ncTitle').value;
      var date = document.getElementById('ncDate').value;
      var start = document.getElementById('ncStart').value;
      var end = document.getElementById('ncEnd').value;
      var zoom = document.getElementById('ncZoom').value;

      if (!title || !date) { alert(_t('adm_amb_fill_title_date', 'Completa t\u00EDtulo y fecha')); return; }

      // Validate: prevent scheduling classes in the past
      var classStartDT = new Date(date + 'T' + (start || '19:00') + ':00');
      var now = new Date();
      if (classStartDT < now) {
        alert(_t('adm_amb_past_date', 'No se puede programar una clase en el pasado. Selecciona una fecha/hora futura.'));
        return;
      }

      // Validate: end time must be after start time
      var startTime = start || '19:00';
      var endTime = end || '21:00';
      if (endTime <= startTime) {
        alert(_t('adm_amb_invalid_time', 'La hora de fin debe ser después de la hora de inicio.'));
        return;
      }

      // Check for schedule conflicts on the same date
      var hasConflict = false;
      if (typeof liveClasses !== 'undefined' && liveClasses.length > 0) {
        for (var ci = 0; ci < liveClasses.length; ci++) {
          var existing = liveClasses[ci];
          if (!existing.fecha) continue;
          var existingDate = existing.fecha.substring(0, 10);
          if (existingDate === date && existing.estado === 'programada') {
            var exStart = (existing.hora_inicio || '').substring(0, 5);
            var exEnd = (existing.hora_fin || '').substring(0, 5);
            // Overlap check: new class starts before existing ends AND new class ends after existing starts
            if (startTime < exEnd && endTime > exStart) {
              hasConflict = true;
              if (!confirm(_t('adm_amb_schedule_conflict', 'Ya existe una clase programada de ') + exStart + ' a ' + exEnd + ' ' + _t('adm_amb_conflict_continue', 'en esta fecha. ¿Deseas continuar de todas formas?'))) {
                return;
              }
              break;
            }
          }
        }
      }

      var newClass = {
        titulo: title,
        fecha: date + 'T' + startTime + ':00',
        hora_inicio: startTime,
        hora_fin: endTime,
        instructor: 'Maestro Mario',
        tipo: 'teoria',
        zoom_link: zoom || '',
        estado: 'programada'
      };

      if (supabaseClient) {
        try {
          await supabaseClient.from('live_classes').insert(newClass);
        } catch(e) { console.error('[Calendario] Save error:', e); }
      }

      liveClasses.push(newClass);
      liveClasses.sort(function(a,b) { return new Date(a.fecha) - new Date(b.fecha); });
      renderCalendar();
      renderStudentCalendar();
      renderDashboardSchedule();

      btn.closest('div[style*="position"]').remove();
      alert(_t('adm_amb_class_scheduled', '\u2705 Clase programada: ') + title);
      notifyStudents('Nueva Clase Programada', title + ' — ' + date, 'clase', 'all');
    }


