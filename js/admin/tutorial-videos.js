  var qInput = card.querySelector('.tvq-question');
  var question = qInput ? qInput.value.trim() : '';
  var opts = [];
  card.querySelectorAll('[class^="tvq-opt-"]').forEach(function(inp) { opts.push(inp.value.trim()); });
  var correct = 0;
  card.querySelectorAll('input[type="radio"]').forEach(function(r) { if (r.checked) correct = parseInt(r.value); });
  var explInput = card.querySelector('[class^="tvq-expl-"]');
  var explanation = explInput ? explInput.value.trim() : '';

  if (!question) { alert(_t('adm_tv_empty_question')); return; }

  // Show loading on the AI button
  var aiBtn = card.querySelectorAll('button')[0]; // first button after input is the AI btn
  // Find the AI button specifically
  var btns = card.querySelectorAll('button');
  for (var b = 0; b < btns.length; b++) { if (btns[b].textContent.indexOf('🤖') !== -1) { aiBtn = btns[b]; break; } }
  var origText = aiBtn.textContent;
  aiBtn.disabled = true; aiBtn.textContent = '⏳';

  try {
    var prompt = 'Eres un experto en HVAC y educación técnica. Revisa esta pregunta de quiz y mejórala.\n\n' +
      'PREGUNTA ACTUAL:\n' + question + '\n' +
      'OPCIONES: A) ' + (opts[0]||'') + ' | B) ' + (opts[1]||'') + ' | C) ' + (opts[2]||'') + ' | D) ' + (opts[3]||'') + '\n' +
      'RESPUESTA CORRECTA: ' + String.fromCharCode(65 + correct) + '\n' +
      'EXPLICACIÓN: ' + (explanation || 'ninguna') + '\n\n' +
      'INSTRUCCIONES:\n' +
      '- Mejora la redacción de la pregunta para que sea más clara y profesional\n' +
      '- Asegúrate de que las opciones incorrectas sean plausibles pero claramente incorrectas\n' +
      '- Las 4 opciones deben tener longitud similar\n' +
      '- La explicación debe ser educativa y concisa\n' +
      '- Mantén todo en español\n' +
      '- Responde SOLO con JSON: {"question":"...","options":["A","B","C","D"],"correct":0,"explanation":"..."}';

    var SB_URL = typeof SUPABASE_URL !== 'undefined' ? SUPABASE_URL : 'https://htklsowiyjwsjnacnvnr.supabase.co';
    var res = await fetch(SB_URL + '/functions/v1/instructor-ai-chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'apikey': SUPABASE_KEY, 'Authorization': 'Bearer ' + (SUPABASE_KEY) },
      body: JSON.stringify({ messages: [{ role: 'user', content: prompt }], system: 'Responde SOLO con JSON válido, sin markdown ni texto extra.', max_tokens: 1000, admin_email: getAdminEmail() })
    });

    var data = await res.json();
    var aiText = data.reply || (data.content && typeof data.content === 'string' ? data.content : '') || '';
    aiText = aiText.replace(/^```json?\s*/i, '').replace(/\s*```$/i, '').trim();

    var jsonMatch = aiText.match(/\{[\s\S]*\}/);
    if (!jsonMatch) throw new Error('No JSON in response');
    var improved = JSON.parse(jsonMatch[0]);

    // Apply improvements to the DOM
    if (improved.question && qInput) qInput.value = improved.question;
    if (improved.options && improved.options.length >= 4) {
      var optInputs = card.querySelectorAll('[class^="tvq-opt-"]');
      for (var j = 0; j < Math.min(4, improved.options.length); j++) {
        if (optInputs[j]) optInputs[j].value = improved.options[j];
      }
    }
    if (typeof improved.correct === 'number') {
      var radios = card.querySelectorAll('input[type="radio"]');
      radios.forEach(function(r) { r.checked = parseInt(r.value) === improved.correct; });
    }
    if (improved.explanation && explInput) explInput.value = improved.explanation;

    // Flash green border to show success
    card.style.borderColor = '#22c55e';
    setTimeout(function() { card.style.borderColor = '#334155'; }, 2000);

  } catch(e) {
    console.error('[Quiz AI] Improve error:', e);
    alert(_t('adm_tv_err_improve') + (e.message || e));
  } finally {
    aiBtn.disabled = false; aiBtn.textContent = origText;
  }
