async function tvGenerateQuiz(videoId) {
  var v = _tvVideos.find(function(x) { return x.id === videoId; });
  if (!v) { alert(_t('adm_tv_video_not_found')); return; }

  // Check for transcript — also try from the edit modal textarea if open
  var transcript = v.transcript || '';
  var transcriptEl = document.getElementById('tvEditTranscript');
  if (transcriptEl && transcriptEl.value.trim().length > transcript.length) {
    transcript = transcriptEl.value.trim();
  }
  if (transcript.length < 100) {
    alert(_t('adm_tv_transcript_needed'));
    return;
  }

  // Calculate number of questions based on duration
  var dur = v.duration_seconds || 600; // default 10 min if unknown
  var numQuestions = Math.max(3, Math.min(15, Math.round(dur / 120)));

  var btn = document.getElementById('tvGenQuizBtn');
  if (btn) { btn.disabled = true; btn.textContent = '⏳ ' + _t('adm_tv_generating'); }

  try {
    var systemPrompt = 'Eres un experto creador de quizzes educativos para técnicos de HVAC. ' +
      'Genera preguntas de opción múltiple basadas ESTRICTAMENTE en el contenido de la transcripción proporcionada. ' +
      'Cada pregunta debe evaluar comprensión real del material del video. ' +
      'Responde ÚNICAMENTE con un JSON array válido (sin markdown, sin explicación extra). ' +
      'Formato exacto de cada objeto: ' +
      '{"question":"texto de la pregunta","options":["A","B","C","D"],"correct":0,"explanation":"por qué es correcta","category":"tema"}. ' +
      'El campo "correct" es el índice (0-3) de la opción correcta. ' +
      'Las opciones incorrectas deben ser plausibles pero claramente incorrectas para quien vio el video. ' +
      'Responde siempre en español.';

    var userMessage = 'Genera exactamente ' + numQuestions + ' preguntas de quiz basadas en esta transcripción de video:\n\n' +
      '--- TRANSCRIPCIÓN ---\n' + transcript.substring(0, 8000) + '\n--- FIN ---\n\n' +
      'Recuerda: responde SOLO con el JSON array, sin markdown ni texto adicional.';

    var aiUrl = (typeof INSTRUCTOR_AI_URL !== 'undefined') ? INSTRUCTOR_AI_URL : 'https://htklsowiyjwsjnacnvnr.supabase.co/functions/v1/instructor-ai-chat';
    var response = await fetch(aiUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'apikey': SUPABASE_KEY, 'Authorization': 'Bearer ' + (SUPABASE_KEY) },
      body: JSON.stringify({
        messages: [{ role: 'user', content: userMessage }],
        system: systemPrompt,
        max_tokens: 4000,
        admin_email: (typeof getAdminEmail === 'function') ? getAdminEmail() : ''
      })
    });

    if (!response.ok) throw new Error('Error de IA: ' + response.status);

    var data = await response.json();
    var aiText = '';
    if (data.reply) {
      aiText = data.reply;
    } else if (data.content && typeof data.content === 'string') {
      aiText = data.content;
    } else if (data.content && Array.isArray(data.content)) {
      aiText = data.content.map(function(b) { return b.text || ''; }).join('');
    } else if (data.choices && data.choices[0]) {
      aiText = data.choices[0].message ? data.choices[0].message.content : (data.choices[0].text || '');
    } else if (typeof data === 'string') {
      aiText = data;
    } else {
      aiText = JSON.stringify(data);
    }
    // Clean markdown fences
    aiText = aiText.replace(/^```json?\s*/i, '').replace(/\s*```$/i, '').trim();

    // Extract JSON array from response
    var jsonMatch = aiText.match(/\[[\s\S]*\]/);
    if (!jsonMatch) throw new Error('La IA no devolvió un JSON válido. Respuesta: ' + aiText.substring(0, 200));

    var questions = JSON.parse(jsonMatch[0]);
    if (!Array.isArray(questions) || questions.length === 0) throw new Error('No se generaron preguntas válidas.');

    // Normalize and validate each question
    questions = questions.filter(function(q) {
      return q.question && Array.isArray(q.options) && q.options.length >= 3 && typeof q.correct === 'number';
    }).map(function(q) {
      return {
        question: q.question,
        options: q.options.slice(0, 4),
        correct: Math.min(q.correct, q.options.length - 1),
        explanation: q.explanation || '',
        category: q.category || ''
      };
    });

    if (questions.length === 0) throw new Error('Ninguna pregunta pasó la validación.');

    // Save to database
    var updRes = await supabaseClient.from('tutorial_videos').update({
      quiz_questions: questions,
      quiz_generated_at: new Date().toISOString()
    }).eq('id', videoId);
    if (updRes.error) throw updRes.error;

    // Update local state
    v.quiz_questions = questions;
    v.quiz_generated_at = new Date().toISOString();

    alert('✅ ' + _t('adm_tv_quiz_success').replace('{n}', questions.length));

    // Refresh edit modal to show updated quiz info
    tvCloseModal();
    tvEditVideo(videoId);

  } catch(e) {
    alert(_t('adm_tv_err_gen_quiz') + e.message);
    if (btn) { btn.disabled = false; btn.textContent = '🤖 ' + _t('adm_tv_gen_quiz'); }
  }
}

