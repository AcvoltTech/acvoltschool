async function tvLoadStudentLibrary(studentEmail) {
  var email = (studentEmail || '').toLowerCase().trim();
  try {
    // Check whitelist
    var accRes = await supabaseClient.from('video_access').select('tier_granted').eq('email', email).limit(1).single();
    if (accRes.error || !accRes.data) return []; // Not whitelisted
    var level = TV_TIER_LEVELS[accRes.data.tier_granted || 'basico'] || 1;

    var res = await supabaseClient.from('tutorial_videos').select('*').eq('active', true).order('sort_order').order('created_at', { ascending: false });
    if (res.error) throw res.error;
    return (res.data || []).filter(function(v) {
      return (TV_TIER_LEVELS[v.required_tier || 'basico'] || 1) <= level;
    });
  } catch(e) {
    console.log('Error loading student library:', e);
    return [];
  }
}

// Check if a student email has video access
async function tvCheckStudentAccess(email) {
  email = (email || '').toLowerCase().trim();
  if (!email) return null;
  try {
    var res = await supabaseClient.from('video_access').select('*').eq('email', email).limit(1).single();
    if (res.error || !res.data) return null;
    return res.data; // { email, tier_granted, name, ... }
  } catch(e) { return null; }
}
