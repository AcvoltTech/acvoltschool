    function ssGroupTickets(tickets) {
      var now = new Date();
      var todayStart = new Date(now.getFullYear(), now.getMonth(), now.getDate());
      var yesterdayStart = new Date(todayStart.getTime() - 86400000);
      var weekStart = new Date(todayStart);
      var dayOfWeek = weekStart.getDay();
      weekStart.setDate(weekStart.getDate() - (dayOfWeek === 0 ? 6 : dayOfWeek - 1));
      var monthStart = new Date(now.getFullYear(), now.getMonth(), 1);
      
      var groups = {
        today: { label: '🔥 HOY — ' + todayStart.toLocaleDateString('es-MX',{weekday:'long',day:'numeric',month:'long'}), tickets: [], openCount: 0 },
        yesterday: { label: '📅 AYER — ' + yesterdayStart.toLocaleDateString('es-MX',{weekday:'long',day:'numeric',month:'long'}), tickets: [], openCount: 0 },
        thisWeek: { label: '📆 ESTA SEMANA — ' + weekStart.toLocaleDateString('es-MX',{day:'numeric',month:'short'}) + ' al ' + todayStart.toLocaleDateString('es-MX',{day:'numeric',month:'short'}), tickets: [], openCount: 0 },
        thisMonth: { label: '📅 ESTE MES — ' + now.toLocaleDateString('es-MX',{month:'long',year:'numeric'}), tickets: [], openCount: 0 },
        older: { label: '🗄️ ANTERIORES', tickets: [], openCount: 0 }
      };
      
      tickets.forEach(function(t) {
        var d = new Date(t.created_at);
        var isOpen = t.estado === 'abierto';
        if (d >= todayStart) {
          groups.today.tickets.push(t);
          if (isOpen) groups.today.openCount++;
        } else if (d >= yesterdayStart) {
          groups.yesterday.tickets.push(t);
          if (isOpen) groups.yesterday.openCount++;
        } else if (d >= weekStart) {
          groups.thisWeek.tickets.push(t);
          if (isOpen) groups.thisWeek.openCount++;
        } else if (d >= monthStart) {
          groups.thisMonth.tickets.push(t);
          if (isOpen) groups.thisMonth.openCount++;
        } else {
          groups.older.tickets.push(t);
          if (isOpen) groups.older.openCount++;
        }
      });
      
      // Only return groups that have tickets
      var result = [];
      ['today','yesterday','thisWeek','thisMonth','older'].forEach(function(key) {
        if (groups[key].tickets.length > 0) result.push(groups[key]);
      });
      return result;
    }

