    // Fuzzy name matching for Invoice2go ↔ Telegram cross-reference
    function _tgNameMatch(name1, name2) {
      if (!name1 || !name2) return false;
      var a = name1.toLowerCase().trim();
      var b = name2.toLowerCase().trim();
      if (a === b) return true;
      // Check if first word matches (first name)
      var aFirst = a.split(' ')[0];
      var bFirst = b.split(' ')[0];
      if (aFirst.length >= 3 && bFirst.length >= 3 && aFirst === bFirst) return true;
      // Check if one contains the other
      if (a.indexOf(b) !== -1 || b.indexOf(a) !== -1) return true;
      // Check first + last name partial
      var aWords = a.split(/\s+/);
      var bWords = b.split(/\s+/);
      var matches = 0;
      aWords.forEach(function(w) { if (w.length >= 3 && bWords.some(function(bw) { return bw.indexOf(w) !== -1 || w.indexOf(bw) !== -1; })) matches++; });
      return matches >= 2;
    }

