    // Normalize phone to digits only
    function _waNormalizePhone(phone) {
      if (!phone) return '';
      return phone.replace(/[^\d]/g, '');
    }

    // Check if two phone numbers match (handles US +1 prefix variations)
    function _waPhonesMatch(p1, p2) {
      if (!p1 || !p2) return false;
      if (p1 === p2) return true;
      // Try matching last 10 digits (US numbers)
      var last10a = p1.length >= 10 ? p1.slice(-10) : p1;
      var last10b = p2.length >= 10 ? p2.slice(-10) : p2;
      return last10a === last10b;
    }

    // Format digits back to readable phone
    function _waFormatPhone(digits) {
      if (!digits) return '';
      if (digits.length === 11 && digits[0] === '1') {
        return '+1 (' + digits.slice(1,4) + ') ' + digits.slice(4,7) + '-' + digits.slice(7);
      }
      if (digits.length === 10) {
        return '(' + digits.slice(0,3) + ') ' + digits.slice(3,6) + '-' + digits.slice(6);
      }
      return '+' + digits;
    }

