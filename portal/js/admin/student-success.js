    function ssGetTimeRange(period) {
      var now = new Date();
      var start = null;
      var label = '';
      if (period === 'today') {
        start = new Date(now.getFullYear(), now.getMonth(), now.getDate());
        label = '📅 ' + _t('adm_ss_today') + ' — ' + now.toLocaleDateString('es-MX', {weekday:'long', day:'numeric', month:'long'});
      } else if (period === 'week') {
        var dayOfWeek = now.getDay();
        var diff = dayOfWeek === 0 ? 6 : dayOfWeek - 1; // Monday start
        start = new Date(now.getFullYear(), now.getMonth(), now.getDate() - diff);
        label = '📆 ' + _t('adm_ss_this_week') + ' — ' + start.toLocaleDateString('es-MX', {day:'numeric',month:'short'}) + ' — ' + now.toLocaleDateString('es-MX', {day:'numeric',month:'short'});
      } else if (period === 'month') {
        start = new Date(now.getFullYear(), now.getMonth(), 1);
        label = '📅 ' + now.toLocaleDateString('es-MX', {month:'long', year:'numeric'});
      } else if (period === 'year') {
        start = new Date(now.getFullYear(), 0, 1);
        label = '📊 ' + now.getFullYear();
      }
      return { start: start, label: label };
    }

