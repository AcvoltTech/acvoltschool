    async function ssDashTotalAudit() {
      // Activate total audit mode UI
      _waAuditMode = true;
      var totalBtn = document.getElementById('ssDashBtnTotal');
      totalBtn.style.background = '#ea580c';
      totalBtn.style.color = 'white';
      totalBtn.style.border = 'none';

      // Reset other filter buttons
      ['ssDashBtnAll','ssDashBtnActive','ssDashBtnLost','ssDashBtnTop','ssDashBtnWA','ssDashBtnTG'].forEach(function(id) {
        var btn = document.getElementById(id);
        if (!btn) return;
        btn.style.background = btn.style.background; // keep original
        btn.style.color = '#64748b';
        btn.style.border = '1px solid #e2e8f0';
        btn.style.background = 'rgba(100,100,100,0.1)';
      });

      var loadEl = document.getElementById('ssDashLoading');
      loadEl.style.display = 'block';
      document.getElementById('ssDashTableBody').innerHTML = '';

      try {
        // Step 1: Load ALL technicians from Supabase
        var _ud_allTechs = await usersDataAdmin('admin_list', { limit: 1000 }); var allTechs = _ud_allTechs.data;
        if (!allTechs || allTechs.length === 0) {
          throw new Error('No se pudieron cargar los técnicos registrados.');
        }

        // Step 2: Build registered students lookup (active paying)
        var regByEmail = {};
        var regByPhone = {};
        if (window._registeredStudents) {
          _registeredStudents.forEach(function(s) {
            if (s.email) regByEmail[s.email.toLowerCase().trim()] = s;
            if (s.phone) {
              var digits = s.phone.replace(/\D/g, '');
              if (digits.length >= 10) regByPhone[digits.slice(-10)] = s;
            }
          });
        }

        // Step 3: Build WhatsApp phone lookup
        var waPhoneSet = {};
        if (window._waGroupData) {
          _waGroupData.phones.forEach(function(p) {
            waPhoneSet[p.slice(-10)] = true;
          });
          // Named contacts — match by first name
          var waNamedNames = (_waGroupData.named || []).map(function(n) { return n.name.toLowerCase(); });
        }

        // Step 4: Build Telegram member lookup
        var tgNameSet = {};
        if (window._telegramMembers) {
          _telegramMembers.forEach(function(name) {
            tgNameSet[name.toLowerCase().trim()] = true;
            // Also store first + last combo for fuzzy match
            var parts = name.toLowerCase().trim().split(/\s+/);
            if (parts.length >= 1) tgNameSet[parts[0]] = true;
          });
        }

        // Step 5: Build failed payments lookup
        var failedByEmail = {};
        if (window._failedPayments) {
          _failedPayments.forEach(function(fp) {
            failedByEmail[fp.email.toLowerCase().trim()] = fp;
          });
        }

        // Step 6: Cross-reference each technician
        var results = [];
        allTechs.forEach(function(tech) {
          var email = (tech.email || '').toLowerCase().trim();
          var name = tech.nombre || '';
          var phone = tech.telefono || '';
          var phoneDigits = phone.replace(/\D/g, '');
          var last10 = phoneDigits.length >= 10 ? phoneDigits.slice(-10) : phoneDigits;

          var result = {
            name: name,
            email: email,
            phone: phone,
            phoneFormatted: phone || '—',
            inWebsite: false,     // Registered as active paying student
            inWhatsApp: false,    // In WhatsApp group
            inTelegram: false,    // In Telegram group
            failedCard: false,    // Has failing card in Stripe
            failData: null,       // Failed payment details
            subDate: '',
            plan: '',
            tags: []
          };

          // Check if active paying student (registered-students-data)
          var regStudent = regByEmail[email] || (last10 ? regByPhone[last10] : null);
          if (regStudent) {
            result.inWebsite = true;
            result.subDate = regStudent.date || '';
            result.plan = regStudent.plan || '';
            result.tags.push('💰 Pagando');
            // Use registered name if technician name is empty
            if (!result.name && regStudent.name) result.name = regStudent.name;
          }

          // Check if in WhatsApp group
          if (last10 && waPhoneSet[last10]) {
            result.inWhatsApp = true;
            result.tags.push('📱 WhatsApp');
          } else if (name && waNamedNames) {
            // Try matching saved contacts by name
            var techFirst = name.toLowerCase().split(' ')[0];
            if (techFirst.length >= 3 && waNamedNames.some(function(wn) { return wn === techFirst || wn.indexOf(techFirst) !== -1; })) {
              result.inWhatsApp = true;
              result.tags.push('📱 WhatsApp');
            }
          }

          // Check if in Telegram group
          if (name) {
            var techNameLower = name.toLowerCase().trim();
            var techFirst = techNameLower.split(' ')[0];
            var techParts = techNameLower.split(/\s+/);
            var inTG = tgNameSet[techNameLower] || tgNameSet[techFirst];
            if (!inTG && window._telegramMembers) {
              // Fuzzy match: check if first + last name matches any TG member
              inTG = _telegramMembers.some(function(tgName) {
                var tgLower = tgName.toLowerCase().trim();
                var tgParts = tgLower.split(/\s+/);
                var matches = 0;
                techParts.forEach(function(tp) {
                  if (tp.length >= 3 && tgParts.some(function(tgp) { return tgp.indexOf(tp) !== -1 || tp.indexOf(tgp) !== -1; })) matches++;
                });
                return matches >= 2;
              });
            }
            if (inTG) {
              result.inTelegram = true;
              result.tags.push('✈️ Telegram');
            }
          }

          // Check failed payments
          if (email) {
            var failData = failedByEmail[email];
            if (failData) {
              result.failedCard = true;
              result.failData = failData;
              result.tags.push('⚠️ Tarjeta ' + failData.fails + 'x');
            }
          }

          // Determine category
          if (result.inWebsite && result.inWhatsApp) {
            result.category = 'full'; // Paying + in group = ideal
          } else if (result.inWebsite && !result.inWhatsApp) {
            result.category = 'paying_no_wa'; // Pays but not in WA group
          } else if (!result.inWebsite && result.inWhatsApp && result.failedCard) {
            result.category = 'wa_card_fail'; // In WA, card failing — need help
          } else if (!result.inWebsite && result.inWhatsApp) {
            result.category = 'wa_no_pay'; // In WA but not paying = freeloader
          } else if (!result.inWebsite && result.inTelegram) {
            result.category = 'tg_no_pay'; // In TG but not paying
          } else if (!result.inWebsite && result.failedCard) {
            result.category = 'card_fail_only'; // Not paying, card failing, not in group
          } else {
            result.category = 'outsider'; // Just registered, not paying, not in any group
          }

          results.push(result);
        });

        // Sort: freeloaders first, card fails, TG no pay, paying without WA, then full
        var catOrder = { outsider: 0, wa_no_pay: 1, wa_card_fail: 2, card_fail_only: 3, tg_no_pay: 4, paying_no_wa: 5, full: 6 };
        results.sort(function(a, b) {
          return (catOrder[a.category] || 99) - (catOrder[b.category] || 99);
        });

        _waAuditResults = results;

        // Count stats
        var full = results.filter(function(r) { return r.category === 'full'; }).length;
        var payingNoWA = results.filter(function(r) { return r.category === 'paying_no_wa'; }).length;
        var waNoPay = results.filter(function(r) { return r.category === 'wa_no_pay'; }).length;
        var waCardFail = results.filter(function(r) { return r.category === 'wa_card_fail'; }).length;
        var cardFailOnly = results.filter(function(r) { return r.category === 'card_fail_only'; }).length;
        var tgNoPay = results.filter(function(r) { return r.category === 'tg_no_pay'; }).length;
        var outsiders = results.filter(function(r) { return r.category === 'outsider'; }).length;
        var totalPaying = results.filter(function(r) { return r.inWebsite; }).length;
        var totalCardFail = waCardFail + cardFailOnly;

        // Update KPIs
        document.getElementById('ssDashTotalStudents').textContent = results.length;
        document.getElementById('ssDashActiveStudents').textContent = totalPaying;
        document.getElementById('ssDashInactiveStudents').textContent = outsiders + waNoPay;
        document.getElementById('ssDashTotalRevenue').textContent = full + ' completos';
        document.getElementById('ssDashAvgRevenue').textContent = totalPaying + '/' + results.length;

        // Update label
        document.getElementById('ssDashReportLabel').innerHTML =
          '📊 ' + _t('ss_total_audit_label','Auditoría Total') + ' — <b>' + results.length + '</b> ' + _t('ss_total_registered','registrados') + ' | ' +
          '✅ <span style="color:#059669;font-weight:bold;">' + full + '</span> ' + _t('ss_total_paying_wa','pagando+WA') + ' | ' +
          '💰 <span style="color:#2563eb;font-weight:bold;">' + payingNoWA + '</span> ' + _t('ss_total_paying_no_wa','pagan sin WA') + ' | ' +
          (totalCardFail > 0 ? '⚠️ <span style="color:#d97706;font-weight:bold;">' + totalCardFail + '</span> ' + _t('ss_card_declined','tarjeta rechazada') + ' | ' : '') +
          '📱 <span style="color:#f59e0b;font-weight:bold;">' + waNoPay + '</span> ' + _t('ss_wa_freeloaders','WA freeloaders') + ' | ' +
          (tgNoPay > 0 ? '✈️ <span style="color:#0088cc;font-weight:bold;">' + tgNoPay + '</span> ' + _t('ss_tg_no_pay','TG sin pagar') + ' | ' : '') +
          '❌ <span style="color:#dc2626;font-weight:bold;">' + outsiders + '</span> ' + _t('ss_only_registered','solo registrados');

        // Render total audit table
        _totalRenderAuditTable(results);

      } catch(e) {
        console.error('[TotalAudit] Error:', e);
        document.getElementById('ssDashTableBody').innerHTML = '<tr><td colspan="8" style="text-align:center;padding:20px;color:#dc2626;">❌ Error: ' + _escHtml(e.message) + '</td></tr>';
      } finally {
        loadEl.style.display = 'none';
      }
    }

