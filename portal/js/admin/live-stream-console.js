function _lscInitPolls(streamId) {
  if (_lscPollChannel) { try { supabaseClient.removeChannel(_lscPollChannel); } catch(e) { console.warn('[LiveStreamConsole]', e.message || e); } }
  _lscPollChannel = supabaseClient.channel('polls-' + streamId);

  _lscPollChannel.on('broadcast', { event: 'poll_vote' }, function(payload) {
    var data = payload.payload;
    if (!data || !data.pollId) return;
    var poll = _lscActivePolls.find(function(p) { return p.id === data.pollId; });
    if (!poll) return;
    if (!poll.voters) poll.voters = {};
    if (poll.voters[data.email]) return;
    poll.voters[data.email] = true;
    if (!poll.votes[data.optionIndex]) poll.votes[data.optionIndex] = 0;
    poll.votes[data.optionIndex]++;
    _lscRenderPollsPanel();
    // Show vote badge on polls tab if admin is on another tab
    var tabPolls = document.getElementById('lsaTabPolls');
    if (tabPolls && tabPolls.style.borderBottomColor !== 'rgb(139, 92, 246)') {
      tabPolls.innerHTML = '📊 <span style="background:#8b5cf6;color:#fff;border-radius:50%;padding:0 5px;font-size:10px;animation:lsa-pulse 1s ease-in-out infinite;">!</span>';
    }
  });

  // Late-joiner support: re-broadcast active poll when a student requests it
  _lscPollChannel.on('broadcast', { event: 'request_poll' }, function() {
    var active = _lscActivePolls.find(function(p) { return !p.closed; });
    if (active) {
      _lscPollChannel.send({
        type: 'broadcast', event: 'new_poll',
        payload: { id: active.id, question: active.question, options: active.options }
      });
    }
  });

  _lscPollChannel.subscribe();
}

