/* ── Normalize name for duplicate detection ────────────────────── */
function _umNormalize(name) {
  if (!name) return '';
  return name.toLowerCase().trim()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ');
}

/* ── Levenshtein distance ──────────────────────────────────────── */
function _umLevenshtein(a, b) {
  if (!a || !b) return 999;
  var m = a.length, n = b.length;
  if (m === 0) return n;
  if (n === 0) return m;
  var d = [];
  for (var i = 0; i <= m; i++) { d[i] = [i]; }
  for (var j = 0; j <= n; j++) { d[0][j] = j; }
  for (i = 1; i <= m; i++) {
    for (j = 1; j <= n; j++) {
      var cost = a[i-1] === b[j-1] ? 0 : 1;
      d[i][j] = Math.min(d[i-1][j] + 1, d[i][j-1] + 1, d[i-1][j-1] + cost);
    }
  }
  return d[m][n];
}

function _umSimilarity(a, b) {
  var maxLen = Math.max(a.length, b.length);
  if (maxLen === 0) return 1;
  return 1 - _umLevenshtein(a, b) / maxLen;
}

/* ── Detect duplicates ─────────────────────────────────────────── */
function _umDetectDuplicates() {
  _umDuplicateEmails.clear();
  var nameMap = {};
  var prefixMap = {};

  _umData.forEach(function(u) {
    var norm = _umNormalize(u.nombre);
    if (norm && norm.length > 2) {
      if (!nameMap[norm]) nameMap[norm] = [];
      nameMap[norm].push(u.email);
    }
    var prefix = (u.email || '').split('@')[0].toLowerCase();
    if (prefix && prefix.length > 2) {
      if (!prefixMap[prefix]) prefixMap[prefix] = [];
      prefixMap[prefix].push(u.email);
    }
  });

  Object.values(nameMap).forEach(function(emails) {
    if (emails.length > 1) emails.forEach(function(e) { _umDuplicateEmails.add(e); });
  });
  Object.values(prefixMap).forEach(function(emails) {
    if (emails.length > 1) emails.forEach(function(e) { _umDuplicateEmails.add(e); });
  });

  var names = _umData.filter(function(u) { return _umNormalize(u.nombre).length > 4; });
  for (var i = 0; i < names.length; i++) {
    var normI = _umNormalize(names[i].nombre);
    for (var j = i + 1; j < names.length; j++) {
      var normJ = _umNormalize(names[j].nombre);
      if (normI === normJ) continue;
      if (_umSimilarity(normI, normJ) >= 0.85) {
        _umDuplicateEmails.add(names[i].email);
        _umDuplicateEmails.add(names[j].email);
      }
    }
  }
}

