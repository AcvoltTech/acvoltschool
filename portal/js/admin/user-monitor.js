/* ── Format date ───────────────────────────────────────────────── */
function _umFormatDate(dateStr) {
  if (!dateStr) return '\u2014';
  try {
    var d = new Date(dateStr);
    return d.toLocaleDateString('es-MX', { day: '2-digit', month: 'short', year: 'numeric' });
  } catch(e) { return dateStr.slice(0, 10); }
}

