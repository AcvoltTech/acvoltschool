async function gkSaveEdit(email) {
  if (!_gkRequireAdmin()) return;

  var nombre = (document.getElementById('gk-edit-nombre').value || '').trim();
  var telefono = (document.getElementById('gk-edit-telefono').value || '').trim();
  var plan = (document.getElementById('gk-edit-plan').value || '').trim();
  var tipo = document.getElementById('gk-edit-tipo').value;
  var amount = parseFloat(document.getElementById('gk-edit-amount').value) || 0;
  var statusVal = document.getElementById('gk-edit-status-val').value;
  var activa = statusVal === 'active';

  // Input validation
  if (amount < 0 || amount > 10000) { alert(_t('adm_gk_amount_range', 'Monto debe ser entre $0 y $10,000')); return; }
  if (nombre.length > 200) { alert(_t('adm_gk_name_too_long', 'Nombre muy largo (max 200 caracteres)')); return; }
  if (telefono && !/^[\d\s\(\)\+\-\.]{0,30}$/.test(telefono)) { alert(_t('adm_gk_phone_invalid', 'Tel\u00E9fono inv\u00E1lido')); return; }
  if (plan.length > 100) { alert(_t('adm_gk_plan_too_long', 'Plan name muy largo (max 100 caracteres)')); return; }
  if (['basico', 'premium'].indexOf(tipo) === -1) { alert(_t('adm_gk_type_invalid', 'Tipo inv\u00E1lido')); return; }

  // Collect groups
  var selectedGroups = [];
  STUDENT_GROUP_DEFS.forEach(function(g) {
    var cb = document.getElementById('gk-edit-grp-' + g.id);
    if (cb && cb.checked) selectedGroups.push(g.id);
  });

  try {
    // 1. Update user profile
    await _gkAdminWrite('upsert_user', 'users', {
      email: email,
      nombre: nombre,
      telefono: telefono
    }, null, 'email');

    // 2. Update membership
    await _gkAdminWrite('upsert_membership', 'memberships', {
      email: email,
      activa: activa,
      tipo: tipo,
      amount: amount
    }, null, 'email');

    // 3. Update groups
    var allStudents = getStudentGroups();
    var found = false;
    allStudents.forEach(function(s) {
      if ((s.email || '').toLowerCase() === email) {
        s.groups = selectedGroups;
        s.name = nombre;
        found = true;
      }
    });
    if (!found) {
      allStudents.push({ email: email, name: nombre, groups: selectedGroups });
    }
    saveStudentGroups(allStudents);

    if (typeof auditLog === 'function') auditLog('student.edit', { target_email: email, activa: activa, groups: selectedGroups });
    _gkClearCache();
    document.getElementById('gk-modal').style.display = 'none';
    await loadGatekeeperData();
  } catch (err) {
    alert(_t('adm_gk_error_saving') + ': ' + (err.message || err));
  }
}

