/* ── Admin Write Helper — calls admin-write Edge Function ─────── */
async function _gkAdminWrite(operation, table, data, match, onConflict) {
  var adminEmail = typeof getAdminEmail === 'function' ? getAdminEmail() : '';
  if (!adminEmail) throw new Error('Admin email not found');
  var sbUrl = typeof SUPABASE_URL !== 'undefined' ? SUPABASE_URL : 'https://htklsowiyjwsjnacnvnr.supabase.co';
  var sbKey = typeof SUPABASE_KEY !== 'undefined' ? SUPABASE_KEY : '';
  var body = { admin_email: adminEmail, operation: operation, table: table, data: data };
  if (match) body.match = match;
  if (onConflict) body.onConflict = onConflict;
  var res = await fetch(sbUrl + '/functions/v1/admin-write', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'apikey': sbKey, 'Authorization': 'Bearer ' + sbKey },
    body: JSON.stringify(body)
  });
  var result = await res.json();
  if (!res.ok || result.error) throw new Error(result.error || 'Admin write failed (' + res.status + ')');
  return result;
}

