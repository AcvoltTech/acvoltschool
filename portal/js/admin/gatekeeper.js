/* ── Cache ──────────────────────────────────────────────────────── */
function _gkClearCache() {
  // Clear ALL per-student cache entries from localStorage
  // This ensures block/unblock actions take effect immediately
  try {
    Object.keys(localStorage).forEach(function(key) {
      if (key.indexOf('maestroac_membership_cache') === 0 ||
          key.indexOf('maestroac_student_groups_') === 0 ||
          key.indexOf('maestroac_acceso_completo_') === 0) {
        localStorage.removeItem(key);
      }
    });
  } catch(e) { console.warn('[Gatekeeper]', e.message || e); }
}
