    await _gkAdminWrite('upsert_user', 'users', {
      email: email,
      nombre: nombre,
      telefono: telefono
    }, null, 'email');

    // 2. Create membership if activate
    if (activate) {
      await _gkAdminWrite('upsert_membership', 'memberships', {
        email: email,
        activa: true,
        tipo: 'basico'
      }, null, 'email');
    }

    // 3. Assign groups
    if (selectedGroups.length > 0) {
      var allStudents = getStudentGroups();
      var found = false;
      allStudents.forEach(function(s) {
        if ((s.email || '').toLowerCase() === email) {
          s.groups = selectedGroups;
          found = true;
        }
      });
      if (!found) {
        allStudents.push({ email: email, name: nombre, groups: selectedGroups });
      }
      saveStudentGroups(allStudents);
    }

    if (typeof auditLog === 'function') auditLog('student.add', { target_email: email, activate: activate, groups: selectedGroups });
