function _gkFiltered() {
  return _gkData.filter(function(s) {
    if (_gkFilterStatus !== 'all' && s.status !== _gkFilterStatus) return false;
    if (_gkFilterGroup !== 'all') {
      if (_gkFilterGroup === 'none') {
        if (s.groups && s.groups.length > 0) return false;
      } else {
        var matchIds = getGroupAndChildren(_gkFilterGroup);
        if (matchIds) {
          var hasMatch = false;
          for (var i = 0; i < matchIds.length; i++) {
            if (s.groups && s.groups.indexOf(matchIds[i]) !== -1) { hasMatch = true; break; }
          }
          if (!hasMatch) return false;
        }
      }
    }
    if (_gkSearch) {
      var hay = (s.nombre + ' ' + s.email + ' ' + (s.telefono || '')).toLowerCase();
      if (hay.indexOf(_gkSearch) === -1) return false;
    }
    return true;
  });
}

